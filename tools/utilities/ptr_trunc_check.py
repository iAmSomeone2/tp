#!/usr/bin/env python3

###
# Lists every place where a pointer-sized integer (uintptr_t, intptr_t, ptrdiff_t) is implicitly
# narrowed to a 32-bit type. On a 64-bit host (Linux, Apple-silicon macOS) such a site either
# drops the upper half of an address (a real bug) or narrows a pointer *difference* or a size,
# which is harmless. The Vita (ILP32) is unaffected either way.
#
# How: every TU in a CMake compile_commands.json is re-parsed with
#   clang++ -fsyntax-only -Wno-everything -Wshorten-64-to-32
# and the warnings whose source type is pointer-sized are kept. Explicit casts such as
# `(u32)(uintptr_t)p` are invisible to the warning; they are deliberate (hashes, IDs, ARAM
# addresses) and are not listed.
#
# Lines that look like a difference or a rounded size are listed as "probably benign"; the
# heuristic only sorts the list, it proves nothing. A TU that fails to parse produces no warnings,
# so such TUs are named in the summary and the script exits with status 1.
#
# Usage:
#   python3 tools/utilities/ptr_trunc_check.py                 # summary on stdout
#   python3 tools/utilities/ptr_trunc_check.py --report docs/port/pointer-truncation.md
#   python3 tools/utilities/ptr_trunc_check.py --db build/cmake/debug/compile_commands.json
###

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WARN = re.compile(r"^(?P<file>[^:]+):(?P<line>\d+):\d+: warning: [^']*'(?P<src>[^']*)'.*? to '(?P<dst>[^']*)'.*\[-Wshorten-64-to-32\]")
PTR_SIZED = re.compile(r"(u?intptr_t|ptrdiff_t)\b")  # also matches __ptrdiff_t
BENIGN = re.compile(r"-\s*\(u?intptr_t\)|\(u?intptr_t\)\([^;]*-|\bOSRoundUp32B\b|\bALIGN_(NEXT|PREV)\b|\bDC\w+Range\b")


def run_one(cxx, entry):
    args = entry.get("arguments") or shlex.split(entry["command"])
    if "-o" in args:
        i = args.index("-o")
        args = args[:i] + args[i + 2:]
    keep = [a for a in args[1:] if not a.startswith("-W") and a not in ("-w", "-c", "-fdiagnostics-color=always")]
    if not any(a.startswith("-std=") for a in keep):
        keep.append("-std=c++20")  # CMake omits it when the configured compiler (GCC 16) defaults to it
    cmd = [cxx] + keep + ["-fsyntax-only", "-Wno-everything", "-Wshorten-64-to-32", "-fno-caret-diagnostics"]
    r = subprocess.run(cmd, cwd=entry["directory"], capture_output=True, text=True)
    return entry["file"], r.returncode, r.stderr


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", default=str(ROOT / "build/cmake/default/compile_commands.json"))
    ap.add_argument("--cxx", default="clang++", help="must be clang: GCC has no -Wshorten-64-to-32")
    ap.add_argument("--jobs", type=int, default=os.cpu_count() or 4)
    ap.add_argument("--report", help="write a markdown report to this path")
    args = ap.parse_args()

    db = json.load(open(args.db))
    print(f"checking {len(db)} translation units …", file=sys.stderr)
    sites = {}  # (relpath, line) -> (src type, dst type)
    failed = []  # TUs that did not parse: their warnings are missing, so the list is incomplete
    with ThreadPoolExecutor(args.jobs) as ex:
        for tu, rc, err in ex.map(lambda e: run_one(args.cxx, e), db):
            if rc != 0:
                failed.append(os.path.relpath(tu, ROOT))
            for l in err.splitlines():
                m = WARN.match(l)
                if m and PTR_SIZED.search(m["src"]):
                    path = os.path.relpath(os.path.realpath(m["file"]), ROOT)
                    sites[(path, int(m["line"]))] = (m["src"], m["dst"])

    benign, review = defaultdict(list), defaultdict(list)
    for (path, line), (src, dst) in sorted(sites.items()):
        try:
            text = (ROOT / path).read_text(errors="replace").splitlines()[line - 1].strip()
        except (OSError, IndexError):
            text = ""
        (benign if BENIGN.search(text) else review)[path].append((line, text, dst))

    n_b = sum(map(len, benign.values()))
    n_r = sum(map(len, review.values()))
    summary = f"{len(sites)} sites narrow a pointer-sized integer to 32 bits: {n_r} to review, {n_b} probably benign."
    if failed:
        summary += f" {len(failed)} TUs did not parse, so this is incomplete: " + ", ".join(sorted(failed)) + "."
    print(summary)
    if args.report:
        write_report(args.report, summary, review, benign)
    sys.exit(1 if failed else 0)


def write_report(report, summary, review, benign):
    out = [
        "# Pointer truncation on 64-bit hosts (generated)\n",
        "Generated by `python3 tools/utilities/ptr_trunc_check.py` from the CMake build's "
        "`compile_commands.json`, with `clang++ -Wshorten-64-to-32`. Only narrowing *from* "
        "`uintptr_t`/`intptr_t`/`ptrdiff_t` is listed; explicit casts are deliberate and not shown. "
        "Background and decisions: [compiler-fixes.md](compiler-fixes.md), item 19.\n",
        f"**{summary}** The split is a text heuristic (a subtraction or rounding on the line), not proof.\n",
    ]
    for title, group in (("To review", review), ("Probably benign (differences and sizes)", benign)):
        out.append(f"## {title}\n")
        for path in sorted(group):
            out.append(f"### `{path}`\n")
            for line, text, dst in group[path]:
                out.append(f"* {line} (to `{dst}`): `{text.replace('`', '')}`")
            out.append("")
    Path(report).write_text("\n".join(out) + "\n")
    print(f"wrote {report}", file=sys.stderr)


if __name__ == "__main__":
    main()
